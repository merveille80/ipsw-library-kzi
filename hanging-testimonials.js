(() => {
  "use strict";

  const section = document.querySelector(".hanging-testimonials");
  if (!section) return;
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  const finePointer = window.matchMedia("(hover: hover) and (pointer: fine)");
  const clamp = (value, limit) => Math.max(-limit, Math.min(limit, value));

  // A damped angular spring. Integrate in small steps after a slow frame so
  // a backgrounded tab cannot inject energy into the pendulum on its return.
  function advanceSpring(angle, velocity, target, elapsed) {
    let remaining = Math.min(elapsed, .064);
    while (remaining > 0) {
      const dt = Math.min(remaining, 1 / 240);
      velocity += ((target - angle) * 210 - velocity * 23) * dt;
      angle += velocity * dt;
      remaining -= dt;
    }
    return { angle, velocity };
  }

  section.querySelectorAll(".hanging-card").forEach(card => {
    const pendulum = card.querySelector(".hanging-card__pendulum");
    const button = card.querySelector(".hanging-card__toggle");
    const front = card.querySelector(".hanging-card__front");
    const back = card.querySelector(".hanging-card__back");
    const rest = parseFloat(getComputedStyle(card).getPropertyValue("--rest-angle")) || 0;
    let angle = rest;
    let velocity = 0;
    let target = rest;
    let frame = 0;
    let lastTime = 0;
    let gesture = null;
    let suppressClick = false;
    let flipped = false;

    function paint() {
      pendulum.style.transform = `rotate(${angle}deg)`;
    }

    function stop() {
      if (frame) cancelAnimationFrame(frame);
      frame = 0;
      lastTime = 0;
    }

    function tick(time) {
      frame = 0;
      const next = advanceSpring(angle, velocity, target, lastTime ? (time - lastTime) / 1000 : 1 / 60);
      angle = next.angle;
      velocity = next.velocity;
      lastTime = time;
      if (Math.abs(angle - target) < .015 && Math.abs(velocity) < .04) {
        angle = target;
        velocity = 0;
        lastTime = 0;
      } else {
        frame = requestAnimationFrame(tick);
      }
      paint();
    }

    function animate() {
      if (reducedMotion.matches || document.hidden || gesture || frame) return;
      frame = requestAnimationFrame(tick);
    }

    function setFlipped(next) {
      flipped = next;
      card.classList.toggle("is-flipped", flipped);
      button.setAttribute("aria-expanded", String(flipped));
      button.setAttribute("aria-label", flipped ? `Revenir au portrait de ${card.dataset.person}` : `Lire l’avis de ${card.dataset.person}`);
      button.setAttribute("aria-describedby", flipped ? back.id : "hangingHelp");
      front.setAttribute("aria-hidden", String(flipped));
      back.setAttribute("aria-hidden", String(!flipped));
      front.inert = flipped;
      back.inert = !flipped;
    }

    button.addEventListener("click", event => {
      // Only suppress the click generated by the completed drag. A subsequent
      // keyboard click (detail === 0) must always remain usable.
      if (suppressClick && event.detail !== 0) {
        suppressClick = false;
        return;
      }
      suppressClick = false;
      setFlipped(!flipped);
    });
    button.addEventListener("keydown", event => {
      if (event.key === "Escape" && flipped) {
        event.preventDefault();
        setFlipped(false);
      }
    });

    button.addEventListener("pointerdown", event => {
      if (!event.isPrimary || event.button !== 0) return;
      suppressClick = false;
      card.classList.add("is-pressed");
      // Native horizontal scrolling belongs to touch users. Angular dragging
      // is reserved for a mouse/pen on a fine-pointer surface.
      if (reducedMotion.matches || !finePointer.matches || event.pointerType === "touch") return;
      stop();
      const bounds = pendulum.getBoundingClientRect();
      gesture = {
        id: event.pointerId,
        startX: event.clientX,
        startAngle: angle,
        radius: Math.max(100, event.clientY - bounds.top),
        moved: false,
        samples: [{ angle, time: event.timeStamp }],
      };
      button.setPointerCapture(event.pointerId);
    });

    button.addEventListener("pointermove", event => {
      if (gesture) {
        if (event.pointerId !== gesture.id) return;
        const dx = event.clientX - gesture.startX;
        gesture.moved ||= Math.abs(dx) > 6;
        card.classList.toggle("is-dragging", gesture.moved);
        // Preserve the angle at the grab point; rotation moves lower points in
        // the opposite horizontal direction, hence the minus sign.
        // A flick may briefly overshoot the drag boundary. Re-grabbing that
        // presentation value must not clamp it to a different starting angle.
        angle = clamp(gesture.startAngle - Math.atan2(dx, gesture.radius) * 180 / Math.PI, Math.max(16, Math.abs(gesture.startAngle)));
        gesture.samples.push({ angle, time: event.timeStamp });
        gesture.samples = gesture.samples.filter(sample => event.timeStamp - sample.time <= 90);
        paint();
        return;
      }
      if (reducedMotion.matches || !finePointer.matches || event.pointerType === "touch") return;
      const bounds = card.getBoundingClientRect();
      target = rest - clamp((event.clientX - bounds.left) / bounds.width - .5, .5) * 5;
      animate();
    });

    function release(event, cancelled = false) {
      card.classList.remove("is-pressed");
      if (!gesture || event.pointerId !== gesture.id) return;
      const active = gesture;
      gesture = null;
      suppressClick = cancelled || active.moved;
      const first = active.samples[0];
      const last = active.samples.at(-1);
      velocity = !cancelled && active.moved && last.time > first.time && event.timeStamp - last.time < 100
        ? clamp((last.angle - first.angle) / ((last.time - first.time) / 1000), 180)
        : 0;
      target = rest;
      card.classList.remove("is-dragging");
      if (button.hasPointerCapture(event.pointerId)) button.releasePointerCapture(event.pointerId);
      animate();
    }

    button.addEventListener("pointerup", event => release(event));
    button.addEventListener("pointercancel", event => release(event, true));
    button.addEventListener("lostpointercapture", event => release(event, true));
    button.addEventListener("pointerleave", () => {
      if (!gesture) {
        card.classList.remove("is-pressed");
        target = rest;
        animate();
      }
    });

    function resetMotion() {
      const pointerId = gesture?.id;
      stop();
      gesture = null;
      card.classList.remove("is-dragging", "is-pressed");
      if (pointerId !== undefined && button.hasPointerCapture(pointerId)) button.releasePointerCapture(pointerId);
      angle = reducedMotion.matches ? 0 : rest;
      velocity = 0;
      target = rest;
      paint();
    }
    reducedMotion.addEventListener("change", resetMotion);
    finePointer.addEventListener("change", resetMotion);
    document.addEventListener("visibilitychange", () => {
      if (document.hidden) resetMotion();
    });
    setFlipped(false);
    resetMotion();
  });
  section.classList.add("hanging-ready");
})();
